def tr(language, key, **kwargs):
    text = TEXT.get(language, TEXT[DEFAULT_LANGUAGE]).get(key, TEXT[DEFAULT_LANGUAGE].get(key, key))
    return text.format(**kwargs) if kwargs else text


def label(language, category, key):
    tables = {
        "status": STATUS_LABELS,
        "diagnosis": DIAGNOSIS_LABELS,
        "task": TASK_LABELS,
        "stage": STAGE_LABELS,
        "mode": MODE_LABELS,
    }
    return tables[category].get(language, tables[category][DEFAULT_LANGUAGE]).get(key, key)
